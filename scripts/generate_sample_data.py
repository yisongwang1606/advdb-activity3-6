"""Deterministic synthetic coursework data. AI-assisted draft prepared with Codex.
All names, emails and activity events below are fictional; this is not real usage.
Run from any directory with Python 3.10+. No external libraries are needed.
"""
from pathlib import Path
from datetime import datetime, timedelta, timezone
import json

root = Path(__file__).resolve().parents[1]
names = [
    "Alex Morgan", "Jordan Lee", "Taylor Chen", "Sam Rivera", "Casey Patel", "Riley Park",
    "Jamie Wilson", "Avery Singh", "Quinn Martin", "Drew Nguyen", "Skyler Brooks", "Reese Kim",
    "Rowan Clark", "Emery Scott", "Parker Lewis", "Finley Adams", "Harper Evans", "Logan Diaz",
    "Cameron Reed", "Blake Turner", "Dakota Price", "Hayden Ross", "Kendall Bell", "Payton Ward"
]
genres = ["Mystery", "Sci-fi", "Comedy", "Drama", "Horror", "Animation", "Documentary", "Reality"]
phrases = ["a cozy mystery in a small town", "surviving alone in space", "a cooking competition",
           "something scary in the woods", "a gentle cartoon for young kids"]
users, events = [], []
for uid, name in enumerate(names, start=1):
    prefs = {
        "favourite_genres": [genres[(uid - 1) % 8], genres[uid % 8]],
        "subtitle_language": ["en", "fr", "es", "zh"][(uid - 1) % 4],
    }
    if uid % 3 == 0:
        prefs["parental_controls"] = {"enabled": True, "maximum_rating": "PG"}
    if uid % 2 == 0:
        prefs["autoplay"] = False
    users.append({"user_id": uid, "full_name": name, "email": f"viewer{uid:02d}@example.com",
                  "country": ["CA", "US", "GB", "AU"][(uid - 1) % 4],
                  "plan": ["Basic", "Standard", "Premium"][(uid - 1) % 3], "preferences": prefs})
    watched = [((uid - 1) * 3 + offset) % 60 + 1 for offset in range(3)]
    base = datetime(2026, 10, 20, 12, 0, tzinfo=timezone.utc) + timedelta(hours=uid)
    payloads = [
        (watched[0], {"event_type": "play", "minutes_watched": 20 + uid, "device": "tv"}),
        (watched[1], {"event_type": "play", "minutes_watched": 30 + 2 * uid, "device": "mobile"}),
        (watched[1], {"event_type": "pause", "paused_at_minute": 10 + uid, "reason": "user_action"}),
        (watched[2], {"event_type": "play", "minutes_watched": 40 + uid, "device": "browser"}),
        (watched[2], {"event_type": "rate", "stars": uid % 5 + 1}),
        (None, {"event_type": "search", "query": phrases[(uid - 1) % len(phrases)], "results_count": 5}),
    ]
    for n, (title_id, event) in enumerate(payloads):
        events.append({"activity_id": len(events) + 1, "user_id": uid, "title_id": title_id,
                       "occurred_at": (base + timedelta(minutes=90 * n)).isoformat(), "event_data": event})

def quote(value):
    return "'" + str(value).replace("'", "''") + "'"
def jsql(value):
    return quote(json.dumps(value, ensure_ascii=True, separators=(",", ":"))) + "::jsonb"

sql = ["-- Deterministic synthetic data generated by scripts/generate_sample_data.py.",
       "-- AI-assisted; all users and events are fictional.", "BEGIN;",
       "INSERT INTO users (user_id, full_name, email, country, plan, preferences) VALUES"]
sql.append(",\n".join(f"({u['user_id']},{quote(u['full_name'])},{quote(u['email'])},{quote(u['country'])},{quote(u['plan'])},{jsql(u['preferences'])})" for u in users))
sql.append("ON CONFLICT (user_id) DO UPDATE SET full_name=EXCLUDED.full_name, email=EXCLUDED.email, country=EXCLUDED.country, plan=EXCLUDED.plan, preferences=EXCLUDED.preferences;")
sql.append("INSERT INTO activity_logs (activity_id, user_id, title_id, occurred_at, event_data) VALUES")
sql.append(",\n".join(f"({e['activity_id']},{e['user_id']},{e['title_id'] if e['title_id'] is not None else 'NULL'},{quote(e['occurred_at'])},{jsql(e['event_data'])})" for e in events))
sql.append("ON CONFLICT (activity_id) DO UPDATE SET user_id=EXCLUDED.user_id, title_id=EXCLUDED.title_id, occurred_at=EXCLUDED.occurred_at, event_data=EXCLUDED.event_data;")
sql.append("COMMIT;")
(root / "sql" / "02_sample_data.sql").write_text("\n".join(sql) + "\n", encoding="utf-8")
(root / "data" / "sample_users.json").write_text(json.dumps(users, indent=2) + "\n", encoding="utf-8")
(root / "data" / "sample_activity.json").write_text(json.dumps(events, indent=2) + "\n", encoding="utf-8")
print(f"Generated {len(users)} synthetic users and {len(events)} synthetic events.")
